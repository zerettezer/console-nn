"""Dataset encoding and tf.data pipelines."""
from __future__ import annotations

import random
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

import numpy as np
import tensorflow as tf

from .config import Config, DataConfig
from .synth import read_jsonl
from .tokenizer import NgramTokenizer


LABEL_TO_CLASS = {"success": 0, "fail": 1, "block": 2, "unknown": 3}


def resolve_split_paths(data_dir: str, split: str) -> Path:
    path = Path(data_dir) / f"{split}.jsonl"
    if not path.exists():
        raise FileNotFoundError(f"missing split: {path}")
    return path


def load_documents(data_dir: str, split: str) -> List[Dict]:
    return read_jsonl(str(resolve_split_paths(data_dir, split)))


def fit_tokenizer(docs: Sequence[Dict], cfg: Config) -> NgramTokenizer:
    tok = NgramTokenizer(cfg.tokenizer)
    tok.fit([[line["text"] for line in doc["lines"]] for doc in docs])
    return tok


def _token_labels(
    doc: Dict,
    line_ids: Sequence[int],
    cfg: DataConfig,
    tok: NgramTokenizer,
) -> List[str]:
    status = doc["status"]
    line_labels = [line["label"] for line in doc["lines"]]
    inherited = "success" if (status == "success" and cfg.inherit_success_context) else "unknown"
    out = []
    for line_id in line_ids:
        label = line_labels[line_id] if line_id < len(line_labels) else "neutral"
        if label == "neutral":
            label = inherited
        out.append(label)
    return out


def _assign_chunk_label(labels: Sequence[str], cfg: DataConfig) -> str:
    present = set(labels)
    for label in cfg.label_priority:
        if label in present:
            return label
    return "unknown"


def encode_document(
    doc: Dict,
    tok: NgramTokenizer,
    cfg: DataConfig,
) -> Tuple[np.ndarray, np.ndarray, int, float]:
    """Encode one document into fixed-size chunks.

    Returns
    -------
    ids          int32 [C, chunk_size]
    chunk_labels int32 [C]          (-1 for fully padded chunks)
    doc_label    int32
    completed    float32
    """
    chunk = cfg.chunk_size
    lines = [line["text"] for line in doc["lines"]]
    ids, line_ids, tokens = tok.encode_document(lines)
    if not ids:
        ids = [tok.pad_id]
        line_ids = [0]
    labels = _token_labels(doc, line_ids, cfg, tok)

    n_chunks = (len(ids) + chunk - 1) // chunk
    if cfg.max_chunks_per_doc and n_chunks > cfg.max_chunks_per_doc:
        n_chunks = cfg.max_chunks_per_doc
    ids_arr = np.zeros((n_chunks, chunk), dtype=np.int32)
    labels_arr = np.zeros((n_chunks,), dtype=np.int32)

    # non-overlapping chunks keep the chunk index aligned with the timeline;
    # overlapping training windows are generated by shifting the start offset.
    for c in range(n_chunks):
        start = c * chunk
        piece = ids[start : start + chunk]
        if not piece:
            break
        ids_arr[c, : len(piece)] = piece
        piece_labels = labels[start : start + len(piece)]
        labels_arr[c] = LABEL_TO_CLASS[_assign_chunk_label(piece_labels, cfg)] + 1

    doc_label = LABEL_TO_CLASS.get(doc["status"], 3)
    completed = 1.0 if doc.get("completed", True) else 0.0
    return ids_arr, labels_arr, doc_label, completed


def encode_with_stride(
    doc: Dict,
    tok: NgramTokenizer,
    cfg: DataConfig,
    stride: int,
) -> Tuple[np.ndarray, np.ndarray, int, float]:
    """Like encode_document but with overlapping chunk windows for training."""
    if stride <= 0 or stride == cfg.chunk_size:
        return encode_document(doc, tok, cfg)

    chunk = cfg.chunk_size
    lines = [line["text"] for line in doc["lines"]]
    ids, line_ids, _ = tok.encode_document(lines)
    if not ids:
        ids = [tok.pad_id]
        line_ids = [0]
    labels = _token_labels(doc, line_ids, cfg, tok)

    starts = list(range(0, max(1, len(ids) - chunk + 1), stride))
    if not starts:
        starts = [0]
    if starts[-1] + chunk < len(ids):
        starts.append(len(ids) - chunk)
    starts = starts[: cfg.max_chunks_per_doc or len(starts)]

    ids_arr = np.zeros((len(starts), chunk), dtype=np.int32)
    labels_arr = np.zeros((len(starts),), dtype=np.int32)
    for c, start in enumerate(starts):
        piece = ids[start : start + chunk]
        ids_arr[c, : len(piece)] = piece
        labels_arr[c] = LABEL_TO_CLASS[
            _assign_chunk_label(labels[start : start + len(piece)], cfg)
        ] + 1
    return ids_arr, labels_arr, LABEL_TO_CLASS.get(doc["status"], 3), (
        1.0 if doc.get("completed", True) else 0.0
    )


def encode_split(
    docs: Sequence[Dict],
    tok: NgramTokenizer,
    cfg: Config,
    stride: Optional[int] = None,
) -> List[Tuple[np.ndarray, np.ndarray, int, float]]:
    stride = cfg.data.eval_stride if stride is None else stride
    return [encode_with_stride(doc, tok, cfg.data, stride) for doc in docs]


def _generator(encoded, cfg: Config):
    def gen():
        for ids, chunk_labels, doc_label, completed in encoded:
            yield (
                ids,
                {
                    "chunk_logits": chunk_labels,
                    "doc_logits": np.int32(doc_label),
                    "completed_logits": np.float32(completed),
                },
            )

    return gen


def make_dataset(
    encoded,
    cfg: Config,
    batch_size: int,
    shuffle: bool = False,
    seed: Optional[int] = None,
) -> tf.data.Dataset:
    output_signature = (
        tf.TensorSpec(shape=(None, cfg.data.chunk_size), dtype=tf.int32),
        {
            "chunk_logits": tf.TensorSpec(shape=(None,), dtype=tf.int32),
            "doc_logits": tf.TensorSpec(shape=(), dtype=tf.int32),
            "completed_logits": tf.TensorSpec(shape=(), dtype=tf.float32),
        },
    )
    ds = tf.data.Dataset.from_generator(
        _generator(encoded, cfg), output_signature=output_signature
    )
    if shuffle:
        ds = ds.shuffle(
            max(1, min(len(encoded), cfg.data.shuffle_buffer)),
            seed=seed if seed is not None else cfg.data.seed,
            reshuffle_each_iteration=True,
        )
    ds = ds.padded_batch(
        batch_size,
        padded_shapes=(
            (None, cfg.data.chunk_size),
            {"chunk_logits": (None,), "doc_logits": (), "completed_logits": ()},
        ),
        drop_remainder=False,
    )
    options = tf.data.Options()
    options.experimental_deterministic = not shuffle
    ds = ds.with_options(options)
    return ds.prefetch(cfg.data.prefetch)


def representative_dataset(
    encoded,
    chunk_window: int,
    n_samples: int,
    seed: int = 7,
    batch: int = 1,
):
    rng = random.Random(seed)
    pool = [item for item in encoded if item[0].shape[0] > 0]
    if not pool:
        pool = encoded

    def gen():
        for _ in range(n_samples):
            ids = pool[rng.randrange(len(pool))][0]
            c = ids.shape[0]
            if c >= chunk_window:
                start = rng.randrange(0, c - chunk_window + 1)
                window = ids[start : start + chunk_window]
            else:
                window = np.zeros((chunk_window, ids.shape[1]), dtype=np.int32)
                window[:c] = ids
            yield [window[None, ...].astype(np.int32)]

    return gen
